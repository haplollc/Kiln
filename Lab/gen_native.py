#!/usr/bin/env python3
"""Wrap each example app in a namespace so all of them compile natively in Kiln Lab.

Examples/Apps/<Name>.swift  ->  KilnLab/Native/<Name>Native.swift  (enum <Name>Native { ... })
plus NativeIndex.swift mapping example names to their native ContentView.

Random calls draw from LabRandom.generator, the same seeded generator Kiln
uses when the Lab passes -seed, so a shuffled deck matches in both modes."""
import os, re, glob
here = os.path.dirname(os.path.abspath(__file__))
src_dir = os.path.join(here, "..", "Examples", "Apps")
out_dir = os.path.join(here, "KilnLab", "Native")
names = []
for path in sorted(glob.glob(os.path.join(src_dir, "*.swift"))):
    name = os.path.splitext(os.path.basename(path))[0]
    text = open(path).read()
    imports = sorted({l.strip() for l in re.findall(r"^import[ \t]+\w+[ \t]*$", text, re.M)} | {"import SwiftUI"})
    body = re.sub(r"^import[ \t]+\w+[ \t]*\n?", "", text, flags=re.M)
    for call in ["shuffled", "shuffle", "randomElement"]:
        body = body.replace(".%s()" % call, ".%s(using: &LabRandom.generator)" % call)
    body = re.sub(r"\b(Int|Double|CGFloat|Float)\.random\(in: ([^()]*?)\)", r"\1.random(in: \2, using: &LabRandom.generator)", body)
    body = body.replace("Bool.random()", "Bool.random(using: &LabRandom.generator)")
    indented = "\n".join(("    " + l) if l.strip() else l for l in body.splitlines())
    out = "// Generated by gen_native.py from Examples/Apps/%s.swift. Do not edit.\n%s\n\nenum %sNative {\n%s\n}\n" % (
        name, "\n".join(imports), name, indented)
    open(os.path.join(out_dir, name + "Native.swift"), "w").write(out)
    names.append(name)
cases = "\n".join('        case "%s": AnyView(%sNative.ContentView())' % (n, n) for n in names)
index = """// Generated by gen_native.py. Do not edit.
import SwiftUI

enum NativeIndex {
    static let names = [%s]

    @MainActor static func view(named name: String) -> AnyView {
        switch name {
%s
        default: AnyView(Text("No native version of \\(name)"))
        }
    }
}
""" % (", ".join('"%s"' % n for n in names), cases)
open(os.path.join(out_dir, "NativeIndex.swift"), "w").write(index)
print("generated", names)
